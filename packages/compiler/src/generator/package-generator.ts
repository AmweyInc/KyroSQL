interface GitlabRegistryOptions {
    host: string;
}

export async function generatePackageJson(options: {
    packageName: string;
    version?: string;
    gitlabRegistry?: GitlabRegistryOptions;
    access?: "public" | "restricted";
}) {
    const pkg: Record<string, unknown> = {
        name: options.packageName,
        version: options.version ?? "1.0.0",
        description: "Generated by KyroSQL",
        main: "dist/index.js",
        types: "dist/index.d.ts",
        files: ["dist"],
        scripts: {
            build: "tsc --project tsconfig.json",
        },
    };

    if (options.gitlabRegistry) {
        const cleanHost = options.gitlabRegistry.host.replace(/^https?:\/\//, "").replace(/\/+$/, "");
        const registryUrl = "https://" + cleanHost + "/api/v4/projects/${CI_PROJECT_ID}/packages/npm/";
        const scope = options.packageName.startsWith("@")
            ? options.packageName.split("/")[0]
            : null;

        pkg.publishConfig = {
            ...(scope ? { [`${scope}:registry`]: registryUrl } : { registry: registryUrl }),
            ...(options.access ? { access: options.access } : {}),
        };
    }

    return JSON.stringify(pkg, null, 2);
}

export function generateTsConfig(): string {
    return JSON.stringify({
        compilerOptions: {
            target: "ES2016",
            module: "commonjs",
            declaration: true,
            declarationMap: false,
            outDir: "dist",
            rootDir: ".",
            strict: false,
            skipLibCheck: true,
        },
        include: ["index.ts", "runtime.ts", "types.ts"],
    }, null, 2);
}
